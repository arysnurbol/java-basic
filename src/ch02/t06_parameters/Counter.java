package ch02.t06_parameters;

/** Тапсырма 06 үшін көмекші класс. Бұл файлды өзгертпе. */
public class Counter {

    private int value;

    public Counter(int value) {
        this.value = value;
    }

    public int getValue() {
        return value;
    }

    public void setValue(int value) {
        this.value = value;
    }
}
